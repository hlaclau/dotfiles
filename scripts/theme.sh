#!/usr/bin/env sh
# Switch the colour theme: theme.sh [list | current | json | apply | recolor SRC DST | <name>]
#
# Palettes live in themes/palettes (one `slot #hex` per line, Catppuccin slot names). The checked-in
# configs are Catppuccin Mocha; they are recoloured (every Mocha hex/rgb value is swapped for the
# same slot of the new palette) into ~/.config/theme/, which the shell and tools pick up. Files
# that tools only read from their own config dir go there instead and are gitignored.
# POSIX sh + awk so it also runs on macOS.
set -eu

DOTFILES="$(cd "$(dirname "$0")/.." && pwd)"
PALETTES="$DOTFILES/themes/palettes"
TEMPLATES="$DOTFILES/themes/templates"
REF="$PALETTES/catppuccin-mocha.palette"
OUT="$HOME/.config/theme"
DEFAULT="catppuccin-mocha"

palette_names() {
  for f in "$PALETTES"/*.palette; do basename "$f" .palette; done
}

current_theme() {
  if [ -f "$OUT/current" ]; then cat "$OUT/current"; else echo "$DEFAULT"; fi
}

# recolor SRC DST: swap every Mocha colour in SRC for the same slot of $PAL
recolor() {
  awk -v verbose="${THEME_VERBOSE:-}" '
    function hex2dec(s,   i, v) {
      v = 0
      for (i = 1; i <= length(s); i++) v = v * 16 + index("0123456789abcdef", substr(s, i, 1)) - 1
      return v
    }
    function rgb(h) {
      return hex2dec(substr(h, 2, 2)) ";" hex2dec(substr(h, 4, 2)) ";" hex2dec(substr(h, 6, 2))
    }
    function load(file, arr,   line, f) {
      while ((getline line < file) > 0) {
        split(line, f, " ")
        if (f[2] ~ /^#[0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]$/) arr[f[1]] = tolower(f[2])
      }
      close(file)
    }
    BEGIN {
      load(ARGV[1], ref)
      load(ARGV[2], tgt)
      for (slot in ref) {
        if (!(slot in tgt)) { print "palette is missing slot " slot > "/dev/stderr"; exit 1 }
        hexmap[ref[slot]] = tgt[slot]
        rgbmap[rgb(ref[slot])] = rgb(tgt[slot])
      }
      ARGV[1] = ""; ARGV[2] = ""
    }
    {
      line = $0; out = ""
      while (match(line, /#[0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]/)) {
        h = tolower(substr(line, RSTART, RLENGTH))
        if (h in hexmap) h = hexmap[h]
        else if (verbose) unmapped[h] = 1
        out = out substr(line, 1, RSTART - 1) h
        line = substr(line, RSTART + RLENGTH)
      }
      line = out line; out = ""
      while (match(line, /rgba?\([0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]/)) {
        h = "#" tolower(substr(line, RSTART + RLENGTH - 6, 6))
        if (h in hexmap) h = hexmap[h]
        out = out substr(line, 1, RSTART + RLENGTH - 7) substr(h, 2)
        line = substr(line, RSTART + RLENGTH)
      }
      line = out line; out = ""
      while (match(line, /38;2;[0-9]+;[0-9]+;[0-9]+/)) {
        k = substr(line, RSTART + 5, RLENGTH - 5)
        if (k in rgbmap) k = rgbmap[k]
        out = out substr(line, 1, RSTART + 4) k
        line = substr(line, RSTART + RLENGTH)
      }
      print out line
    }
    END { for (h in unmapped) print "unmapped colour " h > "/dev/stderr" }
  ' "$REF" "$PAL" "$1" > "$2"
}

# slot NAME: hex value of a slot in $PAL
slot() { awk -v s="$1" '$1 == s && $2 ~ /^#/ { print $2 }' "$PAL"; }
meta() { awk -v s="$1" '$1 == s { sub(/^[^ ]+ /, ""); print }' "$PAL"; }

write_ghostty() {
  {
    echo "# Generated by scripts/theme.sh ($NAME)"
    echo "background = $(slot base)"
    echo "foreground = $(slot text)"
    echo "cursor-color = $(slot rosewater)"
    echo "cursor-text = $(slot crust)"
    echo "selection-background = $(slot surface2)"
    echo "selection-foreground = $(slot text)"
    i=0
    for s in surface1 red green yellow blue pink teal subtext1; do
      echo "palette = $i=$(slot "$s")"; i=$((i + 1))
    done
    for s in surface2 red green yellow blue pink teal subtext0; do
      echo "palette = $i=$(slot "$s")"; i=$((i + 1))
    done
  } > "$OUT/ghostty"
}

write_fzf() {
  c() { slot "$1"; }
  {
    echo "# Generated by scripts/theme.sh ($NAME)"
    echo "FZF_THEME_COLORS=\"--color=bg+:$(c surface0),bg:$(c base),spinner:$(c rosewater),hl:$(c mauve) \\"
    echo "--color=fg:$(c text),header:$(c mauve),info:$(c mauve),pointer:$(c rosewater) \\"
    echo "--color=marker:$(c rosewater),fg+:$(c text),prompt:$(c mauve),hl+:$(c mauve) \\"
    echo "--color=selected-bg:$(c surface1) \\"
    echo "--color=border:$(c surface0),label:$(c text)\""
  } > "$OUT/fzf.zsh"
}

write_env() {
  cat > "$OUT/env.zsh" <<EOT
# Generated by scripts/theme.sh ($NAME); sourced by ~/.zshrc
export THEME_NAME="$NAME"
export STARSHIP_CONFIG="$OUT/starship.toml"
export LG_CONFIG_FILE="$OUT/lazygit.yml"
export BAT_THEME="Theme"
source "$OUT/fzf.zsh"
alias fastfetch='fastfetch -c $OUT/fastfetch.jsonc'
EOT
}

write_nvim() {
  {
    echo "-- Generated by scripts/theme.sh ($NAME)"
    echo "return {"
    echo "  name = \"$NAME\","
    echo "  variant = \"$(meta variant)\","
    echo "  accent = \"$(slot "$(meta accent)")\","
    awk '$2 ~ /^#/ { printf "  %s = \"%s\",\n", $1, $2 }' "$PAL"
    echo "}"
  } > "$OUT/palette.lua"
}

write_palette_json() {
  {
    echo "{"
    awk '$2 ~ /^#/ { printf "  \"%s\": \"%s\",\n", $1, $2 }' "$PAL"
    echo "  \"accent\": \"$(slot "$(meta accent)")\""
    echo "}"
  } > "$OUT/palette.json"
}

# Chrome policy: the base (background) color seeds the browser UI colors, the variant picks dark or light. Chrome only
# reads policies from /etc/opt/chrome/policies/managed, where
# scripts/arch-system.sh creates a user-owned theme.json that is rewritten in place (so Chrome's file
# watcher fires) whenever it is writable
write_chrome() {
  cat > "$OUT/chrome-policy.json" <<EOT
{
  "BrowserThemeColor": "$(slot base)",
  "BrowserColorScheme": "$(meta variant)"
}
EOT
  managed=/etc/opt/chrome/policies/managed/theme.json
  [ -w "$managed" ] && [ ! -L "$managed" ] && cat "$OUT/chrome-policy.json" > "$managed" || true
}

# Discord (Equicord): the midnight theme (https://github.com/refact0r/midnight-discord) with its colors
# taken from the palette. The options live in themes/templates/midnight.theme.css; enable
# "midnight.theme.css" under Equicord's Themes once.
write_discord() {
  dir="$HOME/.config/Equicord/themes"
  [ -d "$dir" ] || return 0
  c() { slot "$1"; }
  acc="$(c "$(meta accent)")"
  rm -f "$dir/system24.theme.css" "$dir/discord-mica.theme.css"
  {
    echo "/* Generated by scripts/theme.sh ($NAME) */"
    cat "$TEMPLATES/midnight.theme.css"
    cat <<EOT

/* color options */
:root {
    --colors: on;

    --text-0: var(--bg-4);
    --text-1: $(c text);
    --text-2: $(c text);
    --text-3: $(c subtext1);
    --text-4: $(c subtext0);
    --text-5: $(c overlay0);

    --bg-1: $(c surface1);
    --bg-2: $(c surface0);
    --bg-3: $(c mantle);
    --bg-4: $(c base);
    --hover: color-mix(in srgb, $(c overlay1) 12%, transparent);
    --active: color-mix(in srgb, $(c overlay1) 22%, transparent);
    --active-2: color-mix(in srgb, $(c overlay1) 32%, transparent);
    --message-hover: var(--hover);

    --accent-1: $acc;
    --accent-2: $acc;
    --accent-3: $acc;
    --accent-4: color-mix(in srgb, $acc 85%, $(c text));
    --accent-5: color-mix(in srgb, $acc 70%, $(c base));
    --accent-new: var(--red-2);
    --mention: linear-gradient(to right, color-mix(in srgb, var(--accent-2), transparent 90%) 40%, transparent);
    --mention-hover: linear-gradient(to right, color-mix(in srgb, var(--accent-2), transparent 95%) 40%, transparent);
    --reply: linear-gradient(to right, color-mix(in srgb, var(--text-3), transparent 90%) 40%, transparent);
    --reply-hover: linear-gradient(to right, color-mix(in srgb, var(--text-3), transparent 95%) 40%, transparent);

    --online: var(--green-2);
    --dnd: var(--red-2);
    --idle: var(--yellow-2);
    --streaming: var(--purple-2);
    --offline: var(--text-4);

    --border-light: var(--hover);
    --border: var(--active);
    --border-hover: var(--accent-2);
    --button-border: color-mix(in srgb, $(c text) 10%, transparent);

EOT
    for n in 1 2 3 4 5; do
      echo "    --red-$n: $(c red); --green-$n: $(c green); --blue-$n: $(c blue); --yellow-$n: $(c yellow); --purple-$n: $(c mauve);"
    done
    echo "}"
  } > "$dir/midnight.theme.css"
}

# Hyprland, hyprlock, quickshell, Kvantum and GTK (Arch desktop only)
apply_desktop() {
  [ "$(uname -s)" = Linux ] && [ -d "$DOTFILES/arch/.config/hypr" ] || return 0
  ARCH="$DOTFILES/arch/.config"

  write_palette_json
  rgba() { slot "$1" | sed 's/^#//'; }
  cat > "$OUT/hypr.lua" <<EOT
-- Generated by scripts/theme.sh ($NAME)
return {
    border_active = "rgba($(rgba lavender)ee)",
    border_inactive = "rgba($(rgba surface1)aa)",
    shadow = "rgba($(rgba crust)ee)",
}
EOT
  recolor "$ARCH/hypr/hyprlock.conf" "$OUT/hyprlock.conf"

  # Kvantum: the Catppuccin Mocha Kvantum theme, recoloured
  kv="$ARCH/Kvantum"
  mkdir -p "$kv/theme-current"
  recolor "$kv/catppuccin-mocha-mauve/catppuccin-mocha-mauve.kvconfig" "$kv/theme-current/theme-current.kvconfig"
  recolor "$kv/catppuccin-mocha-mauve/catppuccin-mocha-mauve.svg" "$kv/theme-current/theme-current.svg"

  apply_gtk
  write_chrome

  # On Wayland GTK takes the theme from gsettings first, so point it at Adwaita (apply_gtk's
  # gtk.css recolors it) and keep the icons and light/dark preference in line
  if command -v gsettings > /dev/null 2>&1; then
    gs() { gsettings set org.gnome.desktop.interface "$@" > /dev/null 2>&1 || true; }
    gs gtk-theme Adwaita
    gs icon-theme "$GTK_ICONS"
    gs cursor-theme capitaine-cursors
    gs color-scheme "prefer-$(meta variant)"
  fi
  pkill -HUP -x xsettingsd > /dev/null 2>&1 || true
  hyprctl reload > /dev/null 2>&1 || true
}

# Switch to the theme's wallpaper through quickshell: themes/wallpapers/<theme>.* if there is one,
# else the `wallpaper` line of the palette (a file in wallpapers/).
# THEME_NO_WALLPAPER=1 keeps the current one.
apply_wallpaper() {
  [ -z "${THEME_NO_WALLPAPER:-}" ] && command -v qs > /dev/null 2>&1 || return 0
  wp=""
  for f in "$DOTFILES/themes/wallpapers/$NAME".*; do
    [ -f "$f" ] && wp="$f" && break
  done
  if [ -z "$wp" ]; then
    name="$(meta wallpaper)"
    [ -n "$name" ] && wp="$DOTFILES/wallpapers/$name"
  fi
  [ -n "$wp" ] && [ -f "$wp" ] || return 0
  qs ipc call wallpaper set "$wp" > /dev/null 2>&1 || true
}

# GTK: the built-in Adwaita theme, recolored. GTK 3 ignores named-color overrides on its baked-in
# Adwaita, so gtk-3.0/gtk.css gets real widget rules (themes/templates/gtk3.css, recolored from
# Mocha); GTK 4 / libadwaita honor the named colors, which go in gtk-4.0/gtk.css.
# Apps pick it up when they start.
apply_gtk() {
  c() { slot "$1"; }
  if [ "$(meta variant)" = light ]; then fg="$(c base)"; dark=0; icons=Papirus-Light; else fg="$(c crust)"; dark=1; icons=Papirus-Dark; fi
  [ -d /usr/share/icons/$icons ] || icons=Papirus-Dark
  accent="$(c "$(meta accent)")"
  GTK_ICONS="$icons"

  {
    echo "/* Generated by scripts/theme.sh ($NAME) */"
    # libadwaita (GTK 4)
    for kv in "accent_bg_color $accent" "accent_fg_color $fg" "accent_color $accent" \
      "destructive_bg_color $(c red)" "destructive_fg_color $fg" "destructive_color $(c red)" \
      "success_bg_color $(c green)" "success_fg_color $fg" "success_color $(c green)" \
      "warning_bg_color $(c yellow)" "warning_fg_color $fg" "warning_color $(c yellow)" \
      "error_bg_color $(c red)" "error_fg_color $fg" "error_color $(c red)" \
      "window_bg_color $(c base)" "window_fg_color $(c text)" \
      "view_bg_color $(c mantle)" "view_fg_color $(c text)" \
      "headerbar_bg_color $(c mantle)" "headerbar_fg_color $(c text)" \
      "headerbar_border_color $(c crust)" "headerbar_backdrop_color $(c base)" \
      "card_bg_color $(c surface0)" "card_fg_color $(c text)" \
      "dialog_bg_color $(c base)" "dialog_fg_color $(c text)" \
      "popover_bg_color $(c surface0)" "popover_fg_color $(c text)" \
      "sidebar_bg_color $(c mantle)" "sidebar_fg_color $(c text)" "sidebar_backdrop_color $(c base)" \
      "secondary_sidebar_bg_color $(c base)" "secondary_sidebar_fg_color $(c text)" \
      "scrollbar_outline_color $(c surface2)" \
      "theme_bg_color $(c base)" "theme_fg_color $(c text)" \
      "theme_base_color $(c mantle)" "theme_text_color $(c text)" \
      "theme_selected_bg_color $accent" "theme_selected_fg_color $fg" \
      "theme_unfocused_bg_color $(c base)" "theme_unfocused_fg_color $(c subtext0)" \
      "theme_unfocused_base_color $(c mantle)" "theme_unfocused_text_color $(c subtext0)" \
      "theme_unfocused_selected_bg_color $(c surface2)" "theme_unfocused_selected_fg_color $(c text)" \
      "insensitive_bg_color $(c base)" "insensitive_fg_color $(c overlay0)" "insensitive_base_color $(c mantle)" \
      "borders $(c surface1)" "unfocused_borders $(c surface0)" \
      "link_color $(c sapphire)" "placeholder_text_color $(c overlay1)" "content_view_bg $(c mantle)" \
      "tooltip_bg_color $(c surface1)" "tooltip_fg_color $(c text)" \
      "osd_bg $(c crust)" "osd_fg $(c text)" \
      "bg_color $(c base)" "fg_color $(c text)" "base_color $(c mantle)" "text_color $(c text)" \
      "selected_bg_color $accent" "selected_fg_color $fg"; do
      set -- $kv
      echo "@define-color $1 $2;"
    done
  } > "$ARCH/gtk-4.0/gtk.css.tmp"
  # gtk-4.0/{gtk.css,gtk-dark.css,assets} used to be symlinks into an installed theme: remove them
  # first, writing through a symlink would modify /usr/share
  rm -f "$ARCH/gtk-4.0/gtk.css" "$ARCH/gtk-4.0/gtk-dark.css" "$ARCH/gtk-4.0/assets"
  mv "$ARCH/gtk-4.0/gtk.css.tmp" "$ARCH/gtk-4.0/gtk.css"
  recolor "$TEMPLATES/gtk3.css" "$ARCH/gtk-3.0/gtk.css.tmp"
  sed -e "s|ACCENT_BG|$accent|g" -e "s|ACCENT_FG|$fg|g" -e "1s|^|/* Generated by scripts/theme.sh ($NAME) */\n|" \
    "$ARCH/gtk-3.0/gtk.css.tmp" > "$ARCH/gtk-3.0/gtk.css"
  rm -f "$ARCH/gtk-3.0/gtk.css.tmp"

  # ~/.config/gtk-3.0 is a real directory when it holds other files (bookmarks), so stow links
  # files one by one and does not know about the generated gtk.css yet
  cfg="$HOME/.config/gtk-3.0"
  if [ -d "$cfg" ] && [ ! -L "$cfg" ] && [ ! -e "$cfg/gtk.css" ] && [ ! -L "$cfg/gtk.css" ]; then
    case "$DOTFILES" in
      "$HOME"/*) ln -s "../..${DOTFILES#"$HOME"}/arch/.config/gtk-3.0/gtk.css" "$cfg/gtk.css" ;;
      *) ln -s "$ARCH/gtk-3.0/gtk.css" "$cfg/gtk.css" ;;
    esac
  fi

  for t in gtk3 gtk4; do
    d=gtk-3.0; [ $t = gtk4 ] && d=gtk-4.0
    sed -e "s|^gtk-theme-name=.*|gtk-theme-name=Adwaita|" \
      -e "s|^gtk-icon-theme-name=.*|gtk-icon-theme-name=$icons|" \
      -e "s|^gtk-application-prefer-dark-theme=.*|gtk-application-prefer-dark-theme=$dark|" \
      "$TEMPLATES/$t-settings.ini" > "$ARCH/$d/settings.ini"
  done
  sed -e "s|^Net/ThemeName .*|Net/ThemeName \"Adwaita\"|" -e "s|^Net/IconThemeName .*|Net/IconThemeName \"$icons\"|" \
    "$TEMPLATES/xsettingsd.conf" > "$ARCH/xsettingsd/xsettingsd.conf"
}

apply() {
  NAME="$1"
  PAL="$PALETTES/$NAME.palette"
  [ -f "$PAL" ] || { echo "Unknown theme: $NAME (try: theme.sh list)" >&2; exit 1; }
  mkdir -p "$OUT"

  # From the checked-in Mocha configs
  recolor "$DOTFILES/shared/.config/starship.toml" "$OUT/starship.toml"
  recolor "$DOTFILES/shared/.config/lazygit/config.yml" "$OUT/lazygit.yml"
  recolor "$DOTFILES/shared/.config/fastfetch/config.jsonc" "$OUT/fastfetch.jsonc"
  recolor "$DOTFILES/shared/.config/bat/themes/CatppuccinMocha.tmTheme" "$DOTFILES/shared/.config/bat/themes/Theme.tmTheme"
  recolor "$DOTFILES/shared/.config/btop/themes/catppuccin_mocha.theme" "$DOTFILES/shared/.config/btop/themes/theme_current.theme"
  mkdir -p "$DOTFILES/shared/.config/yazi/flavors/theme.yazi"
  recolor "$TEMPLATES/yazi-flavor.toml" "$DOTFILES/shared/.config/yazi/flavors/theme.yazi/flavor.toml"

  # Straight from the palette
  write_ghostty
  write_fzf
  write_env
  write_nvim
  write_discord
  apply_desktop
  apply_wallpaper
  echo "$NAME" > "$OUT/current"

  # Reload what is running (best effort)
  command -v bat > /dev/null 2>&1 && bat cache --build > /dev/null 2>&1 || true
  pkill -USR2 -x ghostty > /dev/null 2>&1 || true
  pkill -USR2 -x btop > /dev/null 2>&1 || true

  echo "Theme: $NAME"
  echo "Open a new shell (or run: reload) for the prompt, lazygit and fzf; restart nvim, yazi and GTK apps."
}

# JSON of the current theme and all palettes, for the quickshell theme picker
print_json() {
  printf '{"current": "%s", "themes": [' "$(current_theme)"
  sep=""
  for n in $(palette_names); do
    PAL="$PALETTES/$n.palette"
    printf '%s{"id": "%s", "name": "%s", "variant": "%s", "accent": "%s"' "$sep" "$n" "$(meta name)" "$(meta variant)" "$(slot "$(meta accent)")"
    awk '$2 ~ /^#/ { printf ", \"%s\": \"%s\"", $1, $2 }' "$PAL"
    printf '}'
    sep=", "
  done
  printf ']}\n'
}

case "${1:-list}" in
  list)
    cur="$(current_theme)"
    for n in $(palette_names); do
      if [ "$n" = "$cur" ]; then echo "* $n"; else echo "  $n"; fi
    done
    ;;
  current) current_theme ;;
  json) print_json ;;
  apply) apply "$(current_theme)" ;;
  recolor) PAL="$PALETTES/$(current_theme).palette"; recolor "$2" "$3" ;;
  *) apply "$1" ;;
esac
